"""Live-verified declarative catalog of Hyprland appearance and desktop-behavior options."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True, slots=True)
class OptionSpec:
    id: str
    section: str  # "appearance" | "desktop" | "input"
    group: str
    label: str
    description: str
    type: str  # "bool" | "int" | "float" | "color" | "enum" | "string"
    hyprland_path: str
    getoption_name: str
    min: float | None = None
    max: float | None = None
    step: float | None = None
    enum_values: tuple[str, ...] = ()
    risky: bool = False

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "id": self.id,
            "section": self.section,
            "group": self.group,
            "label": self.label,
            "description": self.description,
            "type": self.type,
            "hyprland_path": self.hyprland_path,
            "getoption_name": self.getoption_name,
            "risky": self.risky,
        }
        if self.min is not None:
            d["min"] = self.min
        if self.max is not None:
            d["max"] = self.max
        if self.step is not None:
            d["step"] = self.step
        if self.enum_values:
            d["enum_values"] = list(self.enum_values)
        return d


