"""Line-oriented edit plan and safe text transformation engine for Hyprland Keybind Studio."""

from __future__ import annotations

import difflib
from dataclasses import dataclass, field
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from backend.models.types import BindRecord

VALID_EDIT_KINDS = frozenset(
    {
        "comment_out",
        "uncomment",
        "delete_line",
        "replace_line",
        "insert_after",
    }
)

LUA_DISABLED_PREFIX = "-- HKS-disabled: "
HYPRLANG_DISABLED_PREFIX = "# HKS-disabled: "


class EditError(Exception):
    """Base error for edit plan operations."""


class NotEditableError(EditError):
    """Raised when attempting to edit a loop-generated or non-editable keybinding."""

    def __init__(self, message: str, *, file: str | None = None, line: int | None = None) -> None:
        super().__init__(message)
        self.file = file
        self.line = line


@dataclass(slots=True)
class LineMismatch:
    file: str
    line_number: int
    expected_text: str
    actual_text: str | None
    reason: str

    def format(self) -> str:
        if self.actual_text is None:
            return f"{self.file}:{self.line_number}: {self.reason} (expected {self.expected_text!r})"
        return (
            f"{self.file}:{self.line_number}: {self.reason} "
            f"(expected {self.expected_text!r}, found {self.actual_text!r})"
        )


class EditConflict(EditError):
    """Raised when expected line contents do not match the current file text."""

    def __init__(self, message: str, mismatches: list[LineMismatch] | None = None) -> None:
        super().__init__(message)
        self.mismatches: list[LineMismatch] = mismatches or []


@dataclass(slots=True)
class EditOp:
    kind: str
    file: str
    line_number: int
    expected_text: str
    new_text: str | None = None
    language: str | None = None
    generated: bool = False

    def resolved_language(self) -> str:
        if self.language in ("lua", "hyprlang"):
            return self.language
        if self.file.endswith(".lua"):
            return "lua"
        return "hyprlang"

    def disabled_prefix(self) -> str:
        return (
            LUA_DISABLED_PREFIX
            if self.resolved_language() == "lua"
            else HYPRLANG_DISABLED_PREFIX
        )


def build_op_for_bind(
    bind: BindRecord,
    kind: str,
    new_text: str | None = None,
    *,
    expected_text_override: str | None = None,
) -> EditOp:
    """Construct an EditOp for a BindRecord, refusing loop-generated binds."""
    if bind.generated:
        raise NotEditableError(
            f"Bind '{bind.id}' ({bind.keys_raw}) is generated by a loop "
            f"({bind.occurrences_at_site} binds at {bind.source_file}:{bind.source_line}) "
            f"and cannot be edited individually. Edit the generating loop at "
            f"{bind.source_file}:{bind.source_line} instead.",
            file=bind.source_file,
            line=bind.source_line,
        )
    return EditOp(
        kind=kind,
        file=bind.source_file,
        line_number=bind.source_line,
        expected_text=(
            expected_text_override
            if expected_text_override is not None
            else bind.original_line
        ),
        new_text=new_text,
        language=bind.language,
        generated=bind.generated,
    )


def _split_line_and_eol(raw_line: str) -> tuple[str, str]:
    if raw_line.endswith("\r\n"):
        return raw_line[:-2], "\r\n"
    if raw_line.endswith("\n") or raw_line.endswith("\r"):
        return raw_line[:-1], raw_line[-1:]
    return raw_line, ""


def _detect_default_eol(raw_lines: list[str]) -> str:
    for rl in raw_lines:
        if rl.endswith("\r\n"):
            return "\r\n"
        if rl.endswith("\n"):
            return "\n"
        if rl.endswith("\r"):
            return "\r"
    return "\n"


def apply_ops_to_text(text: str, ops: list[EditOp]) -> str:
    """Apply a sequence of EditOps to `text` in reverse line order.

    Validates that no op targets a loop-generated bind and that every op's
    `expected_text` matches the exact current line content. Preserves line endings,
    trailing newline presence, indentation, and all untouched bytes.
    """
    if not ops:
        return text

    for op in ops:
        if op.generated:
            raise NotEditableError(
                f"Cannot apply '{op.kind}' at {op.file}:{op.line_number}: "
                f"bind is loop-generated. Edit the generating loop at {op.file}:{op.line_number} instead.",
                file=op.file,
                line=op.line_number,
            )
        if op.kind not in VALID_EDIT_KINDS:
            raise ValueError(f"Unsupported EditOp kind: {op.kind!r}")
        if op.kind in ("replace_line", "insert_after") and op.new_text is None:
            raise ValueError(f"EditOp kind {op.kind!r} requires new_text")

    raw_lines = text.splitlines(keepends=True)
    default_eol = _detect_default_eol(raw_lines)

    # Sort ops in reverse line_number order so earlier line numbers never shift.
    # Use enumerate to preserve relative order if multiple ops share a line_number.
    indexed_ops = list(enumerate(ops))
    indexed_ops.sort(key=lambda pair: (pair[1].line_number, pair[0]), reverse=True)

    # First pass: validate all ops against initial lines to report all mismatches at once,
    # and also validate during reverse application.
    mismatches: list[LineMismatch] = []
    seen_lines: set[int] = set()
    for _, op in indexed_ops:
        idx = op.line_number - 1
        if idx < 0 or idx >= len(raw_lines):
            mismatches.append(
                LineMismatch(
                    file=op.file,
                    line_number=op.line_number,
                    expected_text=op.expected_text,
                    actual_text=None,
                    reason=f"line number {op.line_number} out of range (1..{len(raw_lines)})",
                )
            )
            continue

        if op.line_number in seen_lines:
            mismatches.append(
                LineMismatch(
                    file=op.file,
                    line_number=op.line_number,
                    expected_text=op.expected_text,
                    actual_text=_split_line_and_eol(raw_lines[idx])[0],
                    reason="multiple edit operations target the same line",
                )
            )
            continue
        seen_lines.add(op.line_number)

        current_content, _ = _split_line_and_eol(raw_lines[idx])
        if current_content != op.expected_text:
            mismatches.append(
                LineMismatch(
                    file=op.file,
                    line_number=op.line_number,
                    expected_text=op.expected_text,
                    actual_text=current_content,
                    reason="line content does not match expected_text",
                )
            )
            continue

        if op.kind == "uncomment":
            prefix = op.disabled_prefix()
            stripped = current_content.lstrip(" \t")
            if not current_content.startswith(prefix) and not stripped.startswith(prefix):
                mismatches.append(
                    LineMismatch(
                        file=op.file,
                        line_number=op.line_number,
                        expected_text=op.expected_text,
                        actual_text=current_content,
                        reason=f"line does not start with expected disabled prefix {prefix!r}",
                    )
                )

    if mismatches:
        details = "; ".join(m.format() for m in mismatches)
        raise EditConflict(f"Edit conflict detected ({len(mismatches)} mismatch(es)): {details}", mismatches)

    # Second pass: apply each operation in reverse line order
    for _, op in indexed_ops:
        idx = op.line_number - 1
        current_content, eol = _split_line_and_eol(raw_lines[idx])

        # Re-verify against current line state
        if current_content != op.expected_text:
            mm = LineMismatch(
                file=op.file,
                line_number=op.line_number,
                expected_text=op.expected_text,
                actual_text=current_content,
                reason="line content changed during multi-op application",
            )
            raise EditConflict(f"Edit conflict detected: {mm.format()}", [mm])

        if op.kind == "comment_out":
            prefix = op.disabled_prefix()
            raw_lines[idx] = f"{prefix}{current_content}{eol}"

        elif op.kind == "uncomment":
            prefix = op.disabled_prefix()
            if current_content.startswith(prefix):
                restored = current_content[len(prefix):]
            else:
                leading_len = len(current_content) - len(current_content.lstrip(" \t"))
                leading = current_content[:leading_len]
                after = current_content[leading_len:]
                restored = leading + after[len(prefix):]
            raw_lines[idx] = f"{restored}{eol}"

        elif op.kind == "replace_line":
            assert op.new_text is not None
            raw_lines[idx] = f"{op.new_text}{eol}"

        elif op.kind == "delete_line":
            del raw_lines[idx]

        elif op.kind == "insert_after":
            assert op.new_text is not None
            if eol:
                raw_lines.insert(idx + 1, f"{op.new_text}{eol}")
            else:
                # Target line was the final line of a file with no trailing newline.
                raw_lines[idx] = f"{current_content}{default_eol}"
                raw_lines.insert(idx + 1, op.new_text)

    return "".join(raw_lines)


def generate_unified_diff(
    old_text: str,
    new_text: str,
    file_path: str = "config",
    context_lines: int = 3,
) -> str:
    """Generate a unified diff string between old_text and new_text."""
    old_lines = old_text.splitlines(keepends=True)
    new_lines = new_text.splitlines(keepends=True)
    # Ensure lines passed to unified_diff end with newline for clean diff formatting
    if old_lines and not old_lines[-1].endswith(("\n", "\r")):
        old_lines[-1] = old_lines[-1] + "\n"
    if new_lines and not new_lines[-1].endswith(("\n", "\r")):
        new_lines[-1] = new_lines[-1] + "\n"

    diff_iter = difflib.unified_diff(
        old_lines,
        new_lines,
        fromfile=f"a/{file_path}",
        tofile=f"b/{file_path}",
        n=context_lines,
    )
    return "".join(diff_iter)
